"""Метаморфное тестирование детекции: одно и то же значение в разных написаниях."""
from masker.detect.rules import detect_by_rules
from masker.model import Document, Segment, Anchor

CASES = [
    # (описание, текст, ожидаемый тип)
    ("канон",                    "ИНН 3662103003",                      "inn"),
    ("двоеточие",                "ИНН: 3662103003",                     "inn"),
    ("нбп",                      "ИНН 3662103003",                 "inn"),
    ("разрядка (Word)",          "И Н Н   3 6 6 2 1 0 3 0 0 3",         "inn"),
    ("перенос строки внутри",    "ИНН 36621\n03003",                    "inn"),
    ("узкий пробел",             "ИНН 3662 103003",                "inn"),
    ("мягкий перенос",           "ИНН 36621­03003",                "inn"),
    ("в скобках",                "(ИНН3662103003)",                     "inn"),
    ("слитно с КПП",             "ИНН/КПП 3662103003/366201001",        "inn"),
    ("латинская подмена",        "ИНН 3662103003",                      "inn"),
    ("---",                      "",                                     ""),
    ("счёт канон",               "р/с 40702810100000012345 в банке, БИК 044525225", "bank_account"),
    ("счёт с пробелами",         "р/с 40702 810 1 0000 0012345, БИК 044525225",      "bank_account"),
    ("счёт без БИК рядом",       "расчётный счёт 40702810100000012345",              "bank_account"),
    ("---",                      "",                                     ""),
    ("снилс канон",              "СНИЛС 112-233-445 95",                "snils"),
    ("снилс сплошняком",         "СНИЛС 11223344595",                   "snils"),
    ("снилс точки",              "СНИЛС 112.233.445.95",                "snils"),
    ("---",                      "",                                     ""),
    ("паспорт канон",            "паспорт 20 04 123456",                "passport"),
    ("паспорт серия слитно",     "паспорт серия 2004 № 123456",         "passport"),
    ("паспорт с №",              "паспорт 20 04 №123456",               "passport"),
    ("---",                      "",                                     ""),
    ("телефон канон",            "тел. +7 (473) 250-30-30",             "phone"),
    ("телефон слитно",           "тел. 84732503030",                    "phone"),
    ("телефон с доб",            "тел. +7 473 250-30-30 доб. 118",      "phone"),
    ("телефон точками",          "тел. 8.473.250.30.30",                "phone"),
    ("---",                      "",                                     ""),
    ("почта канон",              "e-mail: info@triema.ru",              "email"),
    ("почта прописью",           "почта: info собака triema точка ru",  "email"),
    ("почта в скобках",          "(info@triema.ru)",                    "email"),
    ("почта с пробелами",        "e-mail: info @ triema.ru",            "email"),
]

def run(text: str):
    segs = [Segment(text=text, anchor=Anchor(fmt="docx", locator=("body", 0)), order=0)]
    return detect_by_rules(segs)

hit = miss = 0
for name, text, want in CASES:
    if not text:
        print()
        continue
    ents = run(text)
    got = {e.type for e in ents}
    ok = want in got
    hit += ok; miss += not ok
    found = ", ".join(sorted(f"{e.type}={e.text!r}" for e in ents)) or "—"
    print(f"{'OK ' if ok else 'MISS'} {name:24} | {text[:44]:<46} | {found[:60]}")
print(f"\nнайдено {hit} из {hit+miss}")
