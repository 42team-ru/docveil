"""Мягкие PII (не числа) на тексте, которого нет в корпусе."""
from masker.detect import DetectAgent, default_detectors
from masker.model import Document, Segment, Anchor

CASES = [
 # (текст, что там на самом деле есть)
 ("Поставщик: ООО «Северный ветер», в лице генерального директора Курбангалеева Рустэма Ильдаровича",
  "ORG + PERSON(редкая фамилия)"),
 ("От имени Покупателя действует Ю. В. Козлова на основании доверенности № 14",
  "PERSON в форме инициалы-впереди"),
 ("Ответственный за приёмку — Ким Ен Бок, тел. отдела 250-30-30",
  "PERSON (несклоняемая корейская)"),
 ("Претензии направлять: 394018, г. Воронеж, ул. Кольцовская, д. 24б, оф. 305",
  "ADDRESS целиком"),
 ("Грузополучатель: филиал АО «Триема» в г. Липецке, склад №3, Универсальный проезд, 12",
  "ORG + ADDRESS"),
 ("Подписал: и.о. начальника управления материально-технического снабжения Пилипенко С.А.",
  "PERSON + должность"),
 ("Контактное лицо со стороны Заказчика — Оксана (внутр. 4417), почта oksana.p@mail.ru",
  "PERSON (одно имя) + EMAIL"),
 ("Работы выполняет субподрядчик — Индивидуальный предприниматель Гурьянов Пётр Семёнович",
  "ORG(ИП) + PERSON"),
 ("Согласовано: Мамедов Э.Г.о., начальник ОТК",
  "PERSON с отчеством 'оглы'"),
 ("Доставка осуществляется силами ТК «Деловые линии» до терминала в Ростове-на-Дону",
  "ORG + LOC"),
 ("Настоящий договор составлен в соответствии с ГОСТ Р 51141-98 и Правилами перевозок",
  "PII НЕТ — проверка на ложные"),
 ("Стороны руководствуются Гражданским кодексом Российской Федерации",
  "PII НЕТ — проверка на ложные"),
]
agent = DetectAgent(default_detectors())
for text, truth in CASES:
    doc = Document(path="x.docx", fmt="docx",
        segments=[Segment(text=text, anchor=Anchor(fmt="docx", locator=("body",0)), order=0)])
    res = agent.detect(doc)
    ents = res.entities if hasattr(res, "entities") else res
    soft = [e for e in sorted(ents, key=lambda x: x.start)
            if e.type in ("person","org_name","address","bank_name")]
    got = " | ".join(f"{e.type}={e.text!r}" for e in soft) or "— НИЧЕГО"
    print(f"\n{text[:92]}")
    print(f"   должно быть: {truth}")
    print(f"   найдено:     {got}")
