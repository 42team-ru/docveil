"""Прогрев локальных моделей при старте веб-слоя.

Зачем. Natasha собирается один раз на процесс (``masker.detect.ner.
natasha_tagger`` под ``lru_cache``), а провайдер OCR проверяет наличие
движка при создании. Без прогрева эта работа достаётся первому живому
прогону: пользователь платит секундами ожидания за то, что сервер мог
сделать до того, как принял первый запрос.

Почему не через ``docker compose exec``. Кэш живёт в процессе, а не на
диске: прогрев в отдельном процессе греет тот процесс и завершается.
Греть нужно ровно тот интерпретатор, который потом будет считать прогоны,
поэтому прогрев висит на ``lifespan`` приложения.

Прогрев никогда не роняет старт. Недоступный OCR-движок — это причина не
обработать скан, а не причина не поднять сервис: DOCX и XLSX не зависят
от него вовсе.
"""

from __future__ import annotations

import logging

# Логгер-потомок uvicorn: у собственного логгера модуля нет обработчика, и
# сообщения INFO о прогреве не попали бы в вывод контейнера вовсе — проверено
# на собранном стенде 14.09.2026. Наследник `uvicorn.error` пишет туда же,
# куда сам сервер, и виден в `docker compose logs`.
logger = logging.getLogger("uvicorn.error").getChild("warmup")

#: Текст для прогона NER: короткий, но с фамилией и организацией, чтобы
#: модель действительно разложилась, а не осталась ленивой ссылкой.
_WARMUP_TEXT = "Директор ООО «Ромашка» Иванов Иван Иванович подписал договор."


def warm_up() -> None:
    """Загрузить локальные модели заранее; ошибки прогрева не фатальны."""
    _warm_ner()
    _warm_ocr()


def _warm_ner() -> None:
    """Собрать Natasha и прогнать через неё один короткий текст."""
    try:
        from masker.detect.ner import natasha_tagger

        natasha_tagger().spans(_WARMUP_TEXT)
    except (ImportError, OSError, RuntimeError, ValueError) as error:
        logger.warning("прогрев NER не удался: %s", error)
    else:
        logger.info("прогрев NER: модель загружена")


def _warm_ocr() -> None:
    """Создать выбранный провайдер OCR, чтобы проверить движок заранее.

    Создание, а не распознавание: ``select_ocr`` поднимает ошибку
    отсутствующего движка уже на этом шаге (см. его докстринг), а гонять
    настоящую картинку через tesseract ради прогрева незачем — веса у
    него лежат в системном пакете и в память процесса не кэшируются.
    """
    try:
        from masker.ocr.select import select_ocr

        provider = select_ocr()
    except (ImportError, OSError, RuntimeError, ValueError) as error:
        logger.warning("прогрев OCR не удался: %s", error)
    else:
        logger.info("прогрев OCR: провайдер %s готов", type(provider).__name__)
