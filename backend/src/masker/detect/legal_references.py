"""Признаки ссылок на нормативные акты, не являющихся персональными данными."""

from __future__ import annotations

import re

#: Склонённые формы «федеральный закон». Это именно вид нормативного акта,
#: а не название стороны договора. Слово «от» после него связывает дату с
#: принятием закона, а не с событием конкретного договора.
_FEDERAL_LAW_RE = re.compile(
    r"\bфедеральн(?:ый|ого|ому|ым|ом|ые|ых|ыми)\s+"
    r"закон(?:а|у|ом|ы|ов|ами|ах|е)?\b",
    flags=re.IGNORECASE,
)
_ADOPTION_PREFIX_RE = re.compile(
    # После вида акта может идти его короткий юрисдикционный квалификатор
    # («Российской Федерации», «РФ»), но дата остаётся датой принятия, только
    # если непосредственно после него следует предлог «от».
    rf"{_FEDERAL_LAW_RE.pattern}(?:\s+[А-ЯЁа-яё]+){{0,3}}\s+от\s*$",
    flags=re.IGNORECASE,
)

# 11.09.2026: в преамбуле `arkhschool-68-183.pdf` правила дат принимали
# реквизиты ПП № 313, 44-ФЗ и распоряжения № 121-р за данные сторон. Вид
# нормативного акта перед непосредственным «от» отделяет их от даты договора,
# доверенности и срока, которые надо маскировать.
_NORMATIVE_ACT_PREFIX_RE = re.compile(
    r"\b(?:"
    r"постановлен\w*|"
    r"распоряжен\w*|"
    r"федеральн\w*\s+закон\w*|"
    r"приказ\w*|"
    r"указ\w*|"
    r"положени\w*|"
    r"стать\w*|"
    r"част\w*|"
    r"пункт\w*"
    r")"
    r"(?:[\s,()«»\"'А-ЯЁа-яё№\-]{0,180})?\s+от\s*$",
    flags=re.IGNORECASE,
)


def is_federal_law_reference(text: str) -> bool:
    """Есть ли в тексте обозначение федерального закона в любой падежной форме."""
    return _FEDERAL_LAW_RE.search(text) is not None


def is_federal_law_adoption_date(text: str, date_start: int) -> bool:
    """Связана ли дата непосредственно с предшествующей ссылкой на закон.

    Проверяем только конструкцию «Федеральным законом от <дата>»: так дата
    поставки или подписания, встретившаяся позднее в том же сегменте, не
    получит иммунитет только из-за упомянутого раньше закона.
    """
    return _ADOPTION_PREFIX_RE.search(text[:date_start]) is not None


def is_normative_act_adoption_date(text: str, date_start: int) -> bool:
    """Связана ли дата с реквизитами нормативного акта.

    Дата исключается лишь когда перед ней непосредственно стоит ``от`` в
    конструкции с видом акта. Ограничение предотвращает иммунитет у более
    поздней даты договора в том же сегменте.
    """
    return _NORMATIVE_ACT_PREFIX_RE.search(text[:date_start]) is not None


def is_public_legal_reference_type(entity_type: str) -> bool:
    """Нужно ли убрать тип из набора маскируемых сущностей.

    11.09.2026: номер федерального закона — общедоступный реквизит акта, а
    не ключ поиска стороны. Сам тип остаётся в модели для карточки договора,
    но не должен дойти до планировщика масок.
    """
    return entity_type == "federal_law"
