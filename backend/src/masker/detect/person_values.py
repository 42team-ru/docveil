"""Формальные признаки значения ``PERSON`` без зависимостей от NER."""

from __future__ import annotations


def is_single_token_uppercase_abbreviation(value: str) -> bool:
    """Вернуть ``True`` для КАПС-аббревиатуры, не являющейся ФИО.

    Один токен из заглавных букв («МИК», «ЕИС», «ЭДО») в контракте —
    сокращение, а не полное имя. Многословные ФИО не затрагиваются: в них
    есть пробел, даже если документ набран капсом.
    """
    return len(value.split()) == 1 and value.isupper()
