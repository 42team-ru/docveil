"""Разбор исходных документов и единственный список поддерживаемых форматов.

Список живёт здесь, а не у каждого вызывающего: поддержка формата — свойство
слоя разбора, и знать о ней должен он один. До 10.09.2026 копий было шесть
(`cli.py`, `bench.py`, `eval.py`, дважды в `graph/nodes.py` и в
`api/services/run_service.py`), и две из них протухли: движок уже умел XLSX,
а CLI и API отвечали «формат не поддерживается». Формат, который работает в
воротах и не работает в продукте, — худший вид расхождения: его не видно ни
одному тесту.
"""

from __future__ import annotations

#: Расширения (в нижнем регистре, с точкой), которые умеет разобрать движок.
SUPPORTED_SUFFIXES = frozenset({".docx", ".pdf", ".xlsx"})

#: Человеческое перечисление для сообщений об ошибке: «DOCX, PDF или XLSX».
SUPPORTED_TITLES = ", ".join(sorted(suffix.lstrip(".").upper() for suffix in SUPPORTED_SUFFIXES))

__all__ = ["SUPPORTED_SUFFIXES", "SUPPORTED_TITLES"]
