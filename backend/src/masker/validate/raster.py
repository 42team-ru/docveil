"""Растровая проверка страниц PDF (план К4-1).

08.09.2026 ворота были зелёными — утечка отсутствовала, сертификат чист,
шрифт не мельче 8 pt, — а на первой странице школьного договора подсветка
маркера была белой (то есть её не было вовсе) и сам маркер
``[ОРГАНИЗАЦИЯ-3]`` уехал на 455 pt влево и на строку вниз (`TASKS.md`,
задача К4, коммит ``195067d``). Оба дефекта — про то, *видно* ли маркер
человеку, а не про утечку исходной строки или про геометрию редакции; ни
одна из существующих метрик (``count_highlight_overlaps``,
``layout_diff``, сертификат) их не измеряет, потому что все они смотрят на
текстовый слой и координаты боксов, а не на то, что реально ляжет на
экран.

Единственный способ поймать «подсветка невидима» или «подпись не там, где
нарисована» — сравнить сам растр. Модуль намеренно не хранит эталонный
PNG: геометрия подсветки/подписи ещё не зафиксирована (М6 в работе прямо
сейчас), и любой эталон устареет от первой же правки рендера, а его
перегенерация — то самое действие, которое прячет дефект. Эталон в
репозитории появляется отдельным шагом (К4-2), когда геометрия перестанет
меняться; этот модуль используется там же.

Три примитива, каждый — отдельно тестируемый и переиспользуемый шаг:

- ``render_page_png`` — детерминированный рендер одной страницы в PNG.
- ``phash`` — перцептивный хэш растра (dHash, устойчив к сжатию PNG и
  субпиксельным сдвигам сглаживания).
- ``diff_ratio`` — доля пикселей, отличающихся между двумя PNG одного
  размера, для случаев, когда нужна не булева оценка «то же/не то же», а
  величина расхождения (например, чтобы отличить «сдвинулась одна буква»
  от «подпись пропала совсем»).
"""

from __future__ import annotations

import io

import pymupdf
from PIL import Image, ImageChops

#: Версия PyMuPDF, на которой калиброваны DPI и пороги ниже. Растеризация
#: (сглаживание шрифтов, порядок обхода примитивов) — деталь реализации
#: MuPDF, не часть его публичного контракта, и между минорными версиями
#: меняется. Детерминизм рендера (тест ``test_render_is_byte_identical``)
#: гарантирован только на этой версии; на другой те же входные данные
#: не обязаны дать побайтово тот же PNG. Значение читается из
#: ``pymupdf.VersionBind`` тем же способом, каким его увидит любой
#: потребитель модуля, чтобы дрейф версии был виден при отладке, а не
#: обнаруживался как необъяснимое падение теста в CI.
EXPECTED_PYMUPDF_VERSION = "1.28.2"

#: DPI рендера. Оба реальных дефекта К4 — отсутствующая заливка на всю
#: область подсветки и сдвиг подписи на 455 pt (десятки символов) и целую
#: строку — на порядки крупнее одного пикселя уже при небольшом DPI, растр
#: не обязан быть высоким, чтобы их поймать. 150 — компромисс между
#: скоростью (рендер страницы А4 кладётся в десятки миллисекунд) и запасом
#: против ложного совпадения из-за огрубления: пробел на всю ширину буквы
#: маркера (кегль ≥ 8 pt, план М1) при 150 DPI — это больше 15 px, что
#: не потеряется при пересчёте в 9×9-миниатюру ``phash``.
RENDER_DPI = 150

#: Сторона миниатюры для перцептивного хэша (dHash сравнивает соседние
#: пиксели по строкам, поэтому нужна сетка (n+1)×n). 8 — стандартный
#: размер dHash: даёт 64-битный хэш, различающий изменения на уровне
#: областей страницы (закраска блока, пропавший текст), но не чувствителен
#: к шуму сжатия PNG на соседних пикселях — ровно то разрешение, которое
#: нужно для дефектов К4 (пропавшая заливка на всю подсветку, подпись,
#: переехавшая в другую область страницы), и не нужно ловить смещение на
#: доли пункта — этим занимается не растровая, а геометрическая проверка
#: (``count_highlight_overlaps``, М5/М6).
_PHASH_GRID = 8

#: Порог доли различающихся пикселей (``diff_ratio``), начиная с которого
#: два растра одной страницы считаются содержательно разными, а не разными
#: из-за шума перекодирования PNG. Калибровано так: страница пуста, если
#: не считать один прямоугольник подсветки и одну короткую подпись, —
#: убрать заливку целиком или переместить подпись в другую строку меняет
#: минимум несколько тысяч пикселей из ~2 млн на странице А4 при 150 DPI,
#: то есть на порядки больше этого порога. Значение сознательно маленькое
#: (не «типичный» порог 0.05 для естественных фотографий), потому что
#: страница документа — это в основном белый фон, и битый пиксель на белом
#: фоне не должен потеряться в большом пороге.
DIFF_RATIO_THRESHOLD = 0.0005

#: Яркость (0-255) в grayscale-разности каналов, ниже которой пиксель
#: считается совпавшим. Не 0: PyMuPDF детерминирован при неизменных входе
#: и версии (см. ``test_render_is_byte_identical``), поэтому для
#: одинаковых страниц этот порог не нужен вовсе — он нужен только при
#: сравнении двух *разных* рендеров (разный контент), чтобы не считать
#: различающимися пиксели на границе сглаженного текста, отличающиеся на
#: 1-2 из 255 из-за порядка обхода примитивов PDF (не связан с байтовым
#: детерминизмом одного и того же контента).
_DIFF_PIXEL_THRESHOLD = 8


def render_page_png(pdf: pymupdf.Document, page: int, dpi: int = RENDER_DPI) -> bytes:
    """Рендерит страницу ``page`` документа ``pdf`` в PNG-байты.

    Рендер жёстко детерминирован при неизменном входном документе и
    версии PyMuPDF (см. ``EXPECTED_PYMUPDF_VERSION``): фиксированный
    ``dpi``, цветовое пространство ``csRGB``, без альфа-канала. Шрифты —
    только встроенные в сам PDF (маркер рендерится шрифтом из
    ``src/masker/data/DejaVuSans.ttf``, а не системным), иначе один и тот
    же документ рисуется по-разному на разных машинах.
    """
    doc_page = pdf[page]
    pixmap = doc_page.get_pixmap(dpi=dpi, colorspace=pymupdf.csRGB, alpha=False)
    return pixmap.tobytes("png")  # type: ignore[no-any-return, no-untyped-call]


def phash(png: bytes) -> int:
    """Перцептивный хэш PNG-растра (разностный хэш, dHash, 64 бита).

    Изображение уменьшается до полутонового прямоугольника
    ``(_PHASH_GRID + 1) × _PHASH_GRID`` и для каждой пары соседних по
    строке пикселей записывается один бит: 1, если левый пиксель ярче
    правого. Устойчив к перекодированию PNG и субпиксельным сдвигам
    сглаживания, чувствителен к тому, что нужно ловить в К4 — пропавшей
    заливке и переехавшему тексту (см. константы выше).
    """
    width = _PHASH_GRID + 1
    image = (
        Image.open(io.BytesIO(png))
        .convert("L")
        .resize((width, _PHASH_GRID), Image.Resampling.LANCZOS)
    )
    pixels = image.tobytes()  # mode "L" — один байт (0-255) на пиксель
    bits = 0
    for row in range(_PHASH_GRID):
        offset = row * width
        for col in range(_PHASH_GRID):
            bits <<= 1
            if pixels[offset + col] > pixels[offset + col + 1]:
                bits |= 1
    return bits


def hamming_distance(a: int, b: int) -> int:
    """Число различающихся бит между двумя хэшами ``phash``."""
    return (a ^ b).bit_count()


def diff_ratio(a: bytes, b: bytes) -> float:
    """Доля пикселей, различающихся между двумя PNG одного размера.

    Разница считается по каналам (``ImageChops.difference``), затем
    переводится в полутон и бинаризуется порогом
    ``_DIFF_PIXEL_THRESHOLD``, чтобы не считать различием шум сглаживания
    на границе одного и того же текста. Требует одинакового размера
    сравниваемых растров — иначе сравнение бессмысленно, и это ошибка
    вызывающего кода, а не повод молча привести к общему размеру.
    """
    image_a = Image.open(io.BytesIO(a)).convert("RGB")
    image_b = Image.open(io.BytesIO(b)).convert("RGB")
    if image_a.size != image_b.size:
        raise ValueError(f"размеры растров не совпадают: {image_a.size} vs {image_b.size}")
    diff = ImageChops.difference(image_a, image_b).convert("L")
    mask = diff.point(lambda value: 255 if value > _DIFF_PIXEL_THRESHOLD else 0)
    histogram = mask.histogram()
    differing_pixels = histogram[255]
    total_pixels = mask.size[0] * mask.size[1]
    return differing_pixels / total_pixels
