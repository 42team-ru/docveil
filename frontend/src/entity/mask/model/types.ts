/** Состояние проверки одной найденной замены. */
export type MaskStatus = "ok" | "pending" | "low";

/** Фрагмент документа, заменённый на маркер. */
export type MaskFragment = {
  id: string;
  /** Тип персональных данных: ИНН, ФИО, АДРЕС… */
  type: string;
  /** Исходный текст до замены. */
  original: string;
  /** Маркер, который встал на его место. */
  marker: string;
  /** Уверенность модели, 0…1. */
  confidence: number;
  page: number;
  /** Сторона договора, к которой относится фрагмент. */
  side?: "поставщик" | "покупатель";
};
