#!/usr/bin/env bash
# Замер прогона тестов: где уходит время и сколько воркеров реально нужно.
#
# Зачем. В `gate.sh` стоит PYTEST_WORKERS=4 по замеру той эпохи, когда весь
# прогон занимал ~13 секунд и цена импорта Natasha в каждом воркере
# доминировала. Сейчас тестов 1800+ и прогон идёт минуты — обстоятельства
# изменились, а число осталось. Этот скрипт даёт факт вместо догадки.
#
# Запускать, когда больше ничего тяжёлого не идёт: параллельный gate или
# второй pytest испортят замер, потому что будут драться за те же ядра.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT/backend" || exit 1

PY=.venv/bin/python
# bc печатает дробь с точкой, а printf в русской локали ждёт запятую и
# ругается «недопустимое число». Числа считаются машиной — значит и
# локаль для них машинная.
export LC_NUMERIC=C
export PYTHONPATH=src
export HF_HUB_OFFLINE=1
export TRANSFORMERS_OFFLINE=1

MARK='not gliner and not e2e'
OUT="${1:-$ROOT/bench-tests-report.txt}"
CORES="$(nproc)"

# Список проверяемых значений: 4 — то, что стоит сейчас; дальше вверх до
# половины ядер. Больше половины смысла не имеет — воркеры начинают
# соперничать за память и за импорт моделей.
CANDIDATES=(4 8 12 16)

exec > >(tee "$OUT") 2>&1

echo "═══════════════════════════════════════════════════════════════"
echo " Замер тестов triema-masker"
echo " $(date '+%d.%m.%Y %H:%M')"
echo "═══════════════════════════════════════════════════════════════"
echo
echo "Ядер в системе: $CORES"
echo "Сейчас в gate.sh: PYTEST_WORKERS=${PYTEST_WORKERS:-4}"
echo "Отбор тестов: -m '$MARK'"
echo

busy() {
    # Чужой прогон исказит замер — предупредить, а не молча испортить числа.
    pgrep -f "pytest" >/dev/null 2>&1 || return 1
    return 0
}

if busy; then
    echo "⚠ ВНИМАНИЕ: уже идёт другой pytest. Замер будет неверным."
    echo "  Дождитесь его завершения и запустите скрипт заново."
    echo
    ps -eo etime,args --sort=start_time | grep pytest | grep -v grep | head -5
    exit 1
fi

echo "───────────────────────────────────────────────────────────────"
echo " 1. Сколько всего тестов и сколько времени на сбор"
echo "───────────────────────────────────────────────────────────────"
COLLECT_START=$(date +%s.%N)
TOTAL="$($PY -m pytest -q -m "$MARK" --collect-only 2>/dev/null | tail -1)"
COLLECT_END=$(date +%s.%N)
echo "Собрано: $TOTAL"
printf 'Время сбора: %.1f с\n' "$(echo "$COLLECT_END - $COLLECT_START" | bc)"
echo

echo "───────────────────────────────────────────────────────────────"
echo " 2. Самые долгие тесты (последовательно, без xdist)"
echo "───────────────────────────────────────────────────────────────"
echo "Это главный вопрос замера: время съедают сотни мелких тестов"
echo "(лечится воркерами) или десяток тяжёлых (воркеры не помогут,"
echo "нужны session-scoped фикстуры и кэш моделей)?"
echo
SEQ_START=$(date +%s.%N)
$PY -m pytest -q -p no:randomly -m "$MARK" --durations=25 2>&1 | tail -35
SEQ_END=$(date +%s.%N)
SEQ_TIME=$(echo "$SEQ_END - $SEQ_START" | bc)
printf '\nПоследовательный прогон целиком: %.1f с\n\n' "$SEQ_TIME"

echo "───────────────────────────────────────────────────────────────"
echo " 3. Сколько воркеров реально выгодно"
echo "───────────────────────────────────────────────────────────────"
printf '%-10s %-14s %-12s %s\n' "воркеров" "режим" "время, с" "против текущего"
printf '%-10s %-14s %-12s %s\n' "────────" "─────────────" "───────────" "───────────────"

BASE=""
for n in "${CANDIDATES[@]}"; do
    if [ "$n" -gt "$CORES" ]; then continue; fi
    for mode in load worksteal; do
        # worksteal ровнее раскидывает неравные по длительности тесты:
        # освободившийся воркер забирает работу у занятого, а не ждёт.
        START=$(date +%s.%N)
        $PY -m pytest -q -n "$n" --dist "$mode" -m "$MARK" >/dev/null 2>&1
        RC=$?
        END=$(date +%s.%N)
        T=$(echo "$END - $START" | bc)
        [ -z "$BASE" ] && BASE="$T"
        DELTA=$(echo "scale=1; ($BASE - $T) / $BASE * 100" | bc)
        STATUS=""
        [ "$RC" -ne 0 ] && STATUS=" (тесты падали!)"
        printf '%-10s %-14s %-12.1f %+.1f%%%s\n' "$n" "$mode" "$T" "$DELTA" "$STATUS"
    done
done

echo
echo "───────────────────────────────────────────────────────────────"
echo " 4. Что с этим делать"
echo "───────────────────────────────────────────────────────────────"
cat <<'HINT'
Читать результат так:

* Если в разделе 2 верхние 10 тестов съедают заметную долю всего
  времени — воркеры почти не помогут, надо чинить именно их: вынести
  сборку Natasha и загрузку моделей в session-scoped фикстуру, а тяжёлые
  PDF-прогоны свести к одному на модуль.

* Если время размазано ровно по сотням тестов — берём то число воркеров
  из раздела 3, после которого выигрыш перестаёт расти, и ставим его в
  gate.sh. Не максимальное, а точку выхода на плато.

* Если worksteal стабильно быстрее load — добавить `--dist worksteal`
  в gate.sh.

Менять gate.sh только по этим числам и обязательно переписать в нём
комментарий с новым замером и датой: там сейчас стоит объяснение про
13 секунд, которое давно неверно.
HINT

echo
echo "Отчёт сохранён: $OUT"
