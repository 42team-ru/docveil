"""Ключ согласованности псевдонимов для `PlanAgent`.

Согласованность требует, чтобы одна и та же сущность во всём документе
получила один и тот же маркер (см. AGENTS.md, «Согласованность
псевдонимов»). `group_key` строится поверх `detect/normalize.normalize_value`
— единственного места, которое уже умеет снимать организационно-правовую
форму по словарю `orgforms.yaml` и кавычки всех видов, сводить ФИО к
«фамилия и.о.», выбрасывать пробелы и дефисы у цифровых типов.

Намеренно **не** переиспользован `profile/keys.merge_key`: он решает другую
задачу (склейка блоков профиля) и режет организационно-правовые формы
захардкоженной регуляркой `_FORMS`, где нет половины словаря `orgforms.yaml`.
Два разных ключа для двух разных задач — нормально; один ключ, который
«почти» подходит обеим, — источник плавающих расхождений между профилем и
маркером.
"""

from __future__ import annotations

from masker.detect.normalize import normalize_value
from masker.model import Entity

#: Префикс сырого ключа при пустой нормализации — см. докстринг `group_key`.
_RAW_PREFIX = "~"


def group_key(entity: Entity) -> str:
    """Вернуть ключ, по которому сущности склеиваются в одну группу маркера.

    Тип всегда входит в ключ первым: одно и то же число, встреченное как
    ИНН и как КПП, не должно получить общий маркер.

    Ловушка: `_normalize_org("ООО")` (см. `detect/normalize.py`) возвращает
    **пустую строку** — организационно-правовая форма без названия. Если
    строить ключ прямо от неё, две разные организации, от которых в тексте
    осталось только «ООО», склеятся в одну группу и получат один маркер.
    Поэтому при пустой нормализации ключ строится от исходного текста в
    нижнем регистре с префиксом `~`, который не может встретиться в
    непустой нормализации (та не начинается на `~`) — совпадение с обычным
    ключом исключено.
    """
    normalized = normalize_value(entity.type, entity.text)
    if not normalized:
        normalized = f"{_RAW_PREFIX}{entity.text.casefold()}"
    return f"{entity.type}:{normalized}"
